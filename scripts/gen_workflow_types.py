"""Generate the TypeScript types for workflow blueprint v2.

Source of truth: the pydantic models in
``src/fim_one/core/workflow/blueprint_v2.py``. Output:
``frontend/src/types/workflow-blueprint.generated.ts``.

    uv run python scripts/gen_workflow_types.py

``tests/test_workflow_blueprint_v2.py`` fails while the committed file is
stale, and the frontend's serializer is typed against these interfaces, so a
backend field change that the frontend has not followed fails ``tsc``.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "frontend" / "src" / "types" / "workflow-blueprint.generated.ts"

HEADER = """\
// GENERATED by scripts/gen_workflow_types.py from
// src/fim_one/core/workflow/blueprint_v2.py — do not edit by hand.
// Regenerate: uv run python scripts/gen_workflow_types.py
"""


def _ref_name(ref: str) -> str:
    return ref.rsplit("/", 1)[-1]


def _ts(schema: dict[str, Any]) -> str:
    if "$ref" in schema:
        return _ref_name(schema["$ref"])
    if "const" in schema:
        return json.dumps(schema["const"])
    if "enum" in schema:
        return " | ".join(json.dumps(v) for v in schema["enum"])
    for key in ("anyOf", "oneOf"):
        if key in schema:
            parts: list[str] = []
            for sub in schema[key]:
                t = _ts(sub)
                if t not in parts:
                    parts.append(t)
            return " | ".join(parts)
    kind = schema.get("type")
    if kind == "string":
        return "string"
    if kind in ("integer", "number"):
        return "number"
    if kind == "boolean":
        return "boolean"
    if kind == "null":
        return "null"
    if kind == "array":
        inner = _ts(schema.get("items", {}))
        return f"Array<{inner}>"
    if kind == "object":
        extra = schema.get("additionalProperties")
        if isinstance(extra, dict):
            return f"Record<string, {_ts(extra)}>"
        return "Record<string, unknown>"
    return "unknown"


def _interface(name: str, schema: dict[str, Any]) -> str:
    required = set(schema.get("required", []))
    lines = [f"export interface {name} {{"]
    for field, sub in schema.get("properties", {}).items():
        optional = "" if field in required else "?"
        lines.append(f"  {field}{optional}: {_ts(sub)}")
    lines.append("}")
    return "\n".join(lines)


def render() -> str:
    """Return the generated TypeScript source."""
    from fim_one.core.workflow.blueprint_v2 import NODE_MODELS, SCHEMA_VERSION, BlueprintV2

    schema = BlueprintV2.model_json_schema()
    defs: dict[str, Any] = schema.pop("$defs", {})
    blocks = [HEADER]
    blocks.append(f"export const BLUEPRINT_SCHEMA_VERSION = {SCHEMA_VERSION} as const\n")
    for name in sorted(defs):
        blocks.append(_interface(name, defs[name]) + "\n")
    blocks.append(_interface("BlueprintV2", schema) + "\n")

    node_names = list(NODE_MODELS)
    blocks.append(
        "export type WorkflowNodeV2 =\n"
        + "\n".join(f"  | {NODE_MODELS[n].__name__}" for n in node_names)
        + "\n"
    )
    blocks.append(
        "export type WorkflowNodeV2Type = WorkflowNodeV2[\"type\"]\n"
    )
    blocks.append(
        "/** The ``data`` model of each node type. */\n"
        "export interface NodeDataByType {\n"
        + "\n".join(
            f"  {n}: {NODE_MODELS[n].model_fields['data'].annotation.__name__}"  # type: ignore[union-attr]
            for n in node_names
        )
        + "\n}\n"
    )
    blocks.append(
        "export const WORKFLOW_NODE_V2_TYPES: readonly WorkflowNodeV2Type[] = [\n"
        + "\n".join(f'  "{n}",' for n in node_names)
        + "\n] as const\n"
    )
    return "\n".join(blocks)


def main() -> None:
    OUT.write_text(render(), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
